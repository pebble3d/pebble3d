#!/usr/bin/env node
// Downloads the playground's large assets (never committed) per
// apps/playground/assets.manifest.json into apps/playground/public/assets/, verifies each
// sha256 and regenerates public/assets/LICENSES.md (committed).
//
// Usage: node scripts/fetch-assets.mjs [--update-hashes] [--allow-derived-mismatch]
//   --update-hashes  download missing files and write their sha256 into the manifest
//                    instead of verifying against it.
//   --allow-derived-mismatch (or PEBBLE3D_ALLOW_DERIVED_MISMATCH=1)
//                    opt-in, for CI: a derived output whose sha256 differs from the manifest
//                    is kept with a warning that prints the observed hash, instead of
//                    failing. Downloads and derive sources stay strict. See
//                    scripts/assets/derived-hash.mjs.
//
// An entry with a `derive` block is not served as downloaded: `url` is its source file
// (verified against `sourceSha256`, cached in node_modules/.cache/pebble3d-assets/), and
// `derive.steps` are argv lists for the pinned derive tool (`deriveTools`) that turn it into
// `file` (placeholders: {source}, {tmp} = a scratch dir, {out}). A multi-source derive lists
// further sources in `derive.sources` ({ key: { url, sha256 } }, each verified and cached the
// same way) and references them as {source:key}. Every derive tool is deterministic, so its
// output is byte-for-byte reproducible and `sha256` verifies it; a failed step leaves no file
// at the served name.
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import {
	mkdir,
	mkdtemp,
	readFile,
	rename,
	rm,
	writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
	allowDerivedMismatch,
	checkDerivedHash,
} from "./assets/derived-hash.mjs";
import { safeName, sourceCachePath } from "./assets/source-cache.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = join(root, "apps/playground/assets.manifest.json");
const assetsDir = join(root, "apps/playground/public/assets");
const sourceCacheDir = join(root, "node_modules/.cache/pebble3d-assets");
// Derive tool name -> argv prefix (argv-only spawn, no shell).
const deriveTools = {
	"splat-transform": [join(root, "node_modules/.bin/splat-transform")],
	// Open-source FBX/TGA -> KTX2 GLB build (assimpjs + KTX-Software); see the script.
	"rocketbox-build": [
		process.execPath,
		join(root, "scripts/assets/build-rocketbox.mjs"),
	],
};
const updateHashes = process.argv.includes("--update-hashes");
const allowMismatch = allowDerivedMismatch();

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

async function download(url, dest, expected) {
	const res = await fetch(url, {
		headers: { "user-agent": "pebble3d-fetch-assets" },
	});
	if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
	const buf = Buffer.from(await res.arrayBuffer());
	const tmp = `${dest}.part`;
	// Verify before the bytes reach their served/cached name.
	if (expected && sha256(buf) !== expected)
		throw new Error(
			`${url}: sha256 mismatch (expected ${expected}, got ${sha256(buf)})`,
		);
	await writeFile(tmp, buf);
	await rename(tmp, dest);
	return buf;
}

function licensesMd(assets) {
	// Columns are padded to equal width (separator dashes too), matching Biome's Markdown
	// table formatting so the generated file passes `pnpm lint` as-is.
	const rows = [
		["File", "License", "Attribution", "Source"],
		...assets.map((a) => [`\`${a.file}\``, a.license, a.attribution, a.url]),
	];
	const widths = rows[0].map((_, c) =>
		Math.max(3, ...rows.map((r) => r[c].length)),
	);
	const fmt = (r) =>
		`| ${r.map((cell, c) => cell.padEnd(widths[c])).join(" | ")} |`;
	const lines = [
		"# Third-party assets",
		"",
		"Generated by `pnpm fetch-assets` from `apps/playground/assets.manifest.json`. Do not edit by hand.",
		"The asset files themselves are not committed; run `pnpm fetch-assets` to download them.",
		"",
		fmt(rows[0]),
		`| ${widths.map((w) => "-".repeat(w)).join(" | ")} |`,
		...rows.slice(1).map(fmt),
		"",
		"## Full licence texts",
		"",
		"- Microsoft Rocketbox (MIT): [`licenses/Microsoft-Rocketbox-MIT.txt`](licenses/Microsoft-Rocketbox-MIT.txt), the text at the pinned commit `0943055`.",
		"- Basis Universal transcoder (Apache-2.0), served at `/basis/` and emitted into `dist/basis/` from three: `apps/playground/licenses/Basis-Apache-2.0.txt`, shipped as `basis/LICENSE.txt`.",
	];
	return `${lines.join("\n")}\n`;
}

/**
 * Downloads (or reuses the cached) source of a derived asset and verifies it. `key` is null
 * for the primary `url`/`sourceSha256`, else a `derive.sources` key ({ url, sha256 }).
 */
async function deriveSource(a, key) {
	const src =
		key === null
			? {
					url: a.url,
					get sha256() {
						return a.sourceSha256;
					},
					set sha256(v) {
						a.sourceSha256 = v;
					},
				}
			: a.derive.sources[key];
	const label = key === null ? a.id : `${a.id} [${key}]`;
	if (typeof src?.url !== "string") throw new Error(`${label}: no source url`);
	const path = sourceCachePath(root, a.id, key, src.url);
	await mkdir(sourceCacheDir, { recursive: true });
	let buf = existsSync(path) ? await readFile(path) : null;
	if (!buf || (src.sha256 && sha256(buf) !== src.sha256)) {
		console.log(`${label}: downloading source ${src.url}`);
		buf = await download(src.url, path, updateHashes ? undefined : src.sha256);
	}
	const hash = sha256(buf);
	if (updateHashes) src.sha256 = hash;
	else if (hash !== src.sha256)
		throw new Error(
			`${label}: source sha256 mismatch (expected ${src.sha256}, got ${hash})`,
		);
	return path;
}

/** Runs `a.derive.steps` to produce `dest` from the verified source. */
async function derive(a, dest) {
	const tool = deriveTools[a.derive.tool];
	if (!tool) throw new Error(`${a.id}: unknown derive tool "${a.derive.tool}"`);
	if (!tool.every((p) => existsSync(p)))
		throw new Error(
			`${a.id}: ${a.derive.tool} is not installed (pnpm install)`,
		);
	const source = await deriveSource(a, null);
	const keyed = {};
	for (const key of Object.keys(a.derive.sources ?? {})) {
		if (!safeName(key)) throw new Error(`${a.id}: bad source key "${key}"`);
		keyed[key] = await deriveSource(a, key);
	}
	const tmp = await mkdtemp(join(tmpdir(), "pebble3d-derive-"));
	const out = `${dest}.part${a.file.slice(a.file.lastIndexOf("."))}`;
	try {
		for (const step of a.derive.steps) {
			const args = step.map((x) =>
				x
					.replace(/\{source:([\w.-]+)\}/g, (_, k) => {
						if (!keyed[k]) throw new Error(`${a.id}: unknown source "${k}"`);
						return keyed[k];
					})
					.replaceAll("{source}", source)
					.replaceAll("{tmp}", tmp)
					.replaceAll("{out}", out),
			);
			console.log(`${a.id}: ${a.derive.tool} ${step.join(" ")}`);
			const r = spawnSync(tool[0], [...tool.slice(1), ...args], {
				stdio: "inherit",
			});
			if (r.status !== 0)
				throw new Error(
					`${a.id}: ${a.derive.tool} exited ${r.status ?? r.signal ?? r.error}`,
				);
		}
		if (!updateHashes && a.sha256) {
			const check = checkDerivedHash({
				id: a.id,
				expected: a.sha256,
				got: sha256(await readFile(out)),
				allow: allowMismatch,
			});
			if (!check.ok) throw new Error(check.error);
			if (check.warning) console.warn(`WARNING ${check.warning}`);
		}
		await rename(out, dest);
	} finally {
		await rm(tmp, { recursive: true, force: true });
		await rm(out, { force: true });
	}
	return readFile(dest);
}

/** Produces `dest` for an entry: a plain download, or a derive run. */
const produce = (a, dest) =>
	a.derive
		? derive(a, dest)
		: download(a.url, dest, updateHashes ? undefined : a.sha256);

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
await mkdir(assetsDir, { recursive: true });

let failed = false;
for (const a of manifest.assets) {
	if (!safeName(a.id)) throw new Error(`bad asset id "${a.id}"`);
	if (!safeName(a.file)) throw new Error(`${a.id}: bad file name "${a.file}"`);
	const dest = join(assetsDir, a.file);
	try {
		let buf = existsSync(dest) ? await readFile(dest) : null;
		let source = "cached";
		if (!buf) {
			if (!a.derive) console.log(`${a.id}: downloading ${a.url}`);
			buf = await produce(a, dest);
			source = a.derive ? "derived" : "downloaded";
		}
		let hash = sha256(buf);
		if (updateHashes) {
			a.sha256 = hash;
			console.log(`${a.id}: sha256 ${hash} (${source}, ${buf.length} bytes)`);
			continue;
		}
		if (!a.sha256) {
			console.error(
				`${a.id}: no sha256 in the manifest; run with --update-hashes`,
			);
			failed = true;
			continue;
		}
		if (a.derive && allowMismatch && hash !== a.sha256) {
			// Already warned when derived; a cached copy from an earlier allowed run is kept.
			if (source === "cached")
				console.warn(
					`WARNING ${checkDerivedHash({ id: a.id, expected: a.sha256, got: hash, allow: true }).warning}`,
				);
			console.log(`${a.id}: kept ${a.file} (${source}, unverified)`);
			continue;
		}
		if (hash !== a.sha256 && source === "cached") {
			console.log(`${a.id}: cached file does not match, re-fetching`);
			buf = await produce(a, dest);
			source = a.derive ? "re-derived" : "re-downloaded";
			hash = sha256(buf);
		}
		if (hash !== a.sha256) {
			await rm(dest, { force: true });
			console.error(
				`${a.id}: sha256 mismatch (expected ${a.sha256}, got ${hash}); file removed`,
			);
			failed = true;
			continue;
		}
		console.log(`${a.id}: verified ${a.file} (${source})`);
	} catch (err) {
		// Fail closed per asset: report, leave no file that could be served unverified, go on.
		if (!updateHashes) await rm(dest, { force: true });
		console.error(
			`${a.id}: FAILED: ${err instanceof Error ? err.message : err}`,
		);
		failed = true;
	}
}

if (updateHashes) {
	await writeFile(manifestPath, `${JSON.stringify(manifest, null, "\t")}\n`);
	console.log(`updated ${manifestPath}`);
}
await writeFile(join(assetsDir, "LICENSES.md"), licensesMd(manifest.assets));
console.log(`wrote ${join(assetsDir, "LICENSES.md")}`);
if (failed) process.exit(1);
