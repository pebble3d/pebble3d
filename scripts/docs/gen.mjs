// Docs generator (`pnpm docs:gen`). Renders docs/scene-reference.md from scene.schema.json,
// fills the generated regions of docs/api-reference.md from the TypeScript sources and
// the wasm .d.ts, and concatenates llms-full.txt from llms.txt and the files it links.
// `generate(root)` is pure (path -> content); the CLI writes, or with `--check` lists
// stale files and exits 1. Output is deterministic: sorted names, no timestamps.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { API, SymbolFlags } from "typescript/unstable/sync";

const SCENE_REF = "docs/scene-reference.md";
const API_REF = "docs/api-reference.md";
const WORLD_DTS = "packages/sdk/wasm/det/engine_core_det.d.ts";

const API_SKELETON = `# API reference

What each package exports, and the methods of the wasm \`World\`; the member lists are generated by \`pnpm docs:gen\`.

## @pebble3d/sdk

<!-- gen:begin api-sdk -->
<!-- gen:end api-sdk -->

## @pebble3d/renderer

<!-- gen:begin api-renderer -->
<!-- gen:end api-renderer -->

## World (wasm)

<!-- gen:begin api-world -->
<!-- gen:end api-world -->
`;

// ---------- markdown helpers ----------

/** Escapes a value for a markdown table cell: no newlines, no bare pipes. */
function cell(s) {
	return String(s ?? "")
		.replace(/\s*\n\s*/g, " ")
		.replace(/\|/g, "\\|")
		.trim();
}

function code(s) {
	return `\`${s}\``;
}

function table(header, rows) {
	const lines = [
		`| ${header.join(" | ")} |`,
		`| ${header.map(() => "---").join(" | ")} |`,
	];
	for (const r of rows) lines.push(`| ${r.map(cell).join(" | ")} |`);
	return lines.join("\n");
}

function region(name, body) {
	return `<!-- gen:begin ${name} -->\n${body.trim()}\n<!-- gen:end ${name} -->`;
}

/** Replaces the body of region `name` in `doc`; throws if its markers are missing. */
function fillRegion(doc, name, body) {
	const re = new RegExp(
		`<!-- gen:begin ${name} -->[\\s\\S]*?<!-- gen:end ${name} -->`,
	);
	if (!re.test(doc)) throw new Error(`gen region "${name}" not found`);
	return doc.replace(re, () => region(name, body));
}

function firstSentence(doc) {
	const text = doc.replace(/\s+/g, " ").trim();
	const m = text.match(/^.*?[.!?](?=\s|$)/);
	return m ? m[0] : text;
}

// ---------- scene reference ----------

const isObj = (s) => s?.type === "object" && s.properties;
const isRecord = (s) =>
	s?.type === "object" && !s.properties && s.additionalProperties;

function constraints(s) {
	const c = [];
	if (s.minLength === 1) c.push("non-empty");
	if (s.exclusiveMinimum !== undefined) c.push(`> ${s.exclusiveMinimum}`);
	// zod's .int() emits +-MAX_SAFE_INTEGER bounds; they carry no information.
	if (s.minimum !== undefined && s.minimum > -Number.MAX_SAFE_INTEGER)
		c.push(`>= ${s.minimum}`);
	if (s.exclusiveMaximum !== undefined) c.push(`< ${s.exclusiveMaximum}`);
	if (s.maximum !== undefined && s.maximum < Number.MAX_SAFE_INTEGER)
		c.push(`<= ${s.maximum}`);
	return c.length ? ` (${c.join(", ")})` : "";
}

/** One-line type of a schema node. Object-like nodes name their section path. */
function typeOf(s, sectionPath) {
	if (!s || s === true) return "any";
	if (s.const !== undefined) return JSON.stringify(s.const);
	if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
	const union = s.anyOf ?? s.oneOf;
	if (union) return union.map((v) => typeOf(v, sectionPath)).join(" | ");
	if (s.type === "array") {
		if (s.prefixItems)
			return `[${s.prefixItems.map((v) => typeOf(v)).join(", ")}]`;
		// sectionPath already names the item section (`entities[]`).
		if (isObj(s.items) && sectionPath && !discriminator(s.items))
			return `object[] (${sectionPath})`;
		const item = typeOf(s.items, sectionPath);
		return /\s/.test(item) ? `(${item})[]` : `${item}[]`;
	}
	if (isObj(s)) {
		const disc = discriminator(s);
		if (disc) return `{ ${disc[0]}: ${JSON.stringify(disc[1].const)} }`;
		return sectionPath ? `object (${sectionPath})` : "object";
	}
	if (isRecord(s)) {
		const key = s.propertyNames?.enum
			? s.propertyNames.enum.map((v) => JSON.stringify(v)).join(" | ")
			: "string";
		return `record<${key}, ${typeOf(s.additionalProperties, sectionPath)}>`;
	}
	return `${s.type}${constraints(s)}`;
}

/** The `[name, schema]` of a const-valued property that tags a union variant, if any. */
function discriminator(s) {
	return Object.entries(s.properties).find(([, f]) => f.const !== undefined);
}

function keyName(s) {
	return s.propertyNames?.enum ? "state" : "name";
}

/** Walks the schema, collecting one section per object (path -> properties). */
function sceneSections(schema) {
	const sections = [];
	const seen = new Map(); // JSON of an object schema -> first section path (dedupes prefab vs entity)

	// Returns the section path the node's object form is documented under, or undefined.
	function visit(s, p) {
		if (!s || typeof s !== "object") return undefined;
		const union = s.anyOf ?? s.oneOf;
		if (union) {
			const objs = union.filter(
				(v) => isObj(v) || v.anyOf || v.oneOf || isRecord(v),
			);
			for (const v of objs) {
				const disc = isObj(v) && discriminator(v);
				visit(
					v,
					disc ? `${p} (${disc[0]}: ${JSON.stringify(disc[1].const)})` : p,
				);
			}
			return objs.length ? p : undefined;
		}
		if (s.type === "array" && s.items && !s.prefixItems)
			return visit(s.items, `${p}[]`) && `${p}[]`;
		if (isRecord(s))
			return (
				visit(s.additionalProperties, `${p}.<${keyName(s)}>`) &&
				`${p}.<${keyName(s)}>`
			);
		if (!isObj(s)) return undefined;
		const key = JSON.stringify(s);
		if (seen.has(key)) return seen.get(key);
		seen.set(key, p);
		const section = { path: p, description: s.description, rows: [] };
		sections.push(section);
		const required = new Set(s.required ?? []);
		// entities before prefabs so shared shapes are documented under entities[].
		const names = Object.keys(s.properties);
		if (p === "scene")
			names.sort((a, b) => (a === "prefabs") - (b === "prefabs") || 0);
		for (const name of names) {
			const f = s.properties[name];
			const childPath = p === "scene" ? name : `${p}.${name}`;
			const sub = visit(f, childPath);
			const def =
				f.default !== undefined
					? code(JSON.stringify(f.default))
					: required.has(name)
						? "required"
						: "";
			section.rows.push({ name, f, sub, def });
		}
		return p;
	}
	visit(schema, "scene");

	// Types reference the section a child object landed in (which may be a deduped earlier one).
	return sections.map(({ path: p, description, rows }) => ({
		path: p,
		description,
		rows: rows.map(({ name, f, sub, def }) => [
			code(name),
			code(typeOf(f, sub)),
			def,
			f.description ?? "",
		]),
	}));
}

function sceneReference(root) {
	const schema = JSON.parse(
		readFileSync(path.join(root, "packages/sdk/scene.schema.json"), "utf8"),
	);
	const parts = [
		"Generated from `packages/sdk/scene.schema.json`. One table per object; nested objects are named by path (`entities[].body.collider`), `<name>` is a record key, and `a | b` is a union or enum.",
	];
	for (const s of sceneSections(schema)) {
		parts.push(`### ${s.path}`);
		if (s.description) parts.push(cell(s.description));
		parts.push(table(["field", "type", "default", "description"], s.rows));
	}
	return `# Scene reference

Every field of a Pebble3D scene JSON file: type, default and meaning.

${region("scene", parts.join("\n\n"))}
`;
}

// ---------- API lists (TypeScript 7 API) ----------

const KINDS = [
	[SymbolFlags.Class, "class"],
	[SymbolFlags.Function, "function"],
	[SymbolFlags.Interface, "interface"],
	[SymbolFlags.TypeAlias, "type"],
	[SymbolFlags.Enum, "enum"],
	[SymbolFlags.Variable, "const"],
];

/**
 * A function's signature as written in its source (`(e: Prefab) => Body`), so named
 * aliases stay instead of the checker's expanded structural types.
 */
function declaredSignature(program, sym) {
	const handle = sym.declarations[0];
	const node = handle.resolve();
	const text = program
		.getSourceFile(handle.path)
		.text.slice(node.pos, node.body ? node.body.pos : node.end);
	const m = text.match(/function\*?\s*[\w$]+\s*([\s\S]*)$/);
	if (!m) throw new Error(`cannot read the signature of ${sym.name}`);
	const sig = m[1]
		.replace(/\/\*[\s\S]*?\*\//g, "")
		.replace(/\/\/[^\n]*/g, "")
		.replace(/\s+/g, " ")
		.replace(/,\s*\)/g, ")")
		.replace(/\(\s+/g, "(")
		.replace(/;\s*$/, "")
		.trim();
	// `<T>(a: A): R` -> `<T>(a: A) => R`: split at the colon after the parameter list.
	let depth = 0;
	for (let i = 0; i < sig.length; i++) {
		const ch = sig[i];
		if (ch === "(" || ch === "<" || ch === "{" || ch === "[") depth++;
		else if (
			ch === ")" ||
			(ch === ">" && sig[i - 1] !== "=") ||
			ch === "}" ||
			ch === "]"
		) {
			depth--;
			if (depth === 0 && ch === ")") {
				const rest = sig.slice(i + 1).trim();
				return rest.startsWith(":")
					? `${sig.slice(0, i + 1)} => ${rest.slice(1).trim()}`
					: sig;
			}
		}
	}
	return sig;
}

/** Longest declared shape (interface body, type alias, class constructor) shown in the type column. */
const SHAPE_MAX = 140;

/** Source text of a declaration with comments stripped and whitespace collapsed. */
function declText(program, sym) {
	const handle = sym.declarations[0];
	const node = handle.resolve();
	return program
		.getSourceFile(handle.path)
		.text.slice(node.pos, node.end)
		.replace(/\/\*[\s\S]*?\*\//g, "")
		.replace(/\/\/[^\n]*/g, "")
		.replace(/\s+/g, " ")
		.replace(/;\s*}/g, " }")
		.trim();
}

/** The text from the bracket at `open` through its matching close, or null. */
function balanced(text, open) {
	const pairs = { "(": ")", "{": "}" };
	const close = pairs[text[open]];
	let depth = 0;
	for (let i = open; i < text.length; i++) {
		if (text[i] === text[open]) depth++;
		else if (text[i] === close && --depth === 0) return text.slice(open, i + 1);
	}
	return null;
}

/**
 * A short declared shape for the type column: an interface's members
 * (`{ sceneId: string; desc: EntityDescJson }`), a type alias's right-hand side, or a
 * class's constructor parameters. Empty when it would not fit in a table cell.
 */
function declaredShape(program, sym, kind) {
	const text = declText(program, sym);
	let shape = "";
	if (kind === "interface") {
		const m = text.match(/\binterface\s+[\w$]+\s*/);
		if (m) shape = text.slice(m.index + m[0].length);
	} else if (kind === "type") {
		const m = text.match(/\btype\s+[\w$]+\s*(<[^=]*>)?\s*=\s*/);
		if (m) shape = text.slice(m.index + m[0].length).replace(/;$/, "");
	} else if (kind === "class") {
		const m = text.match(/\bconstructor\s*\(/);
		const params = m ? balanced(text, m.index + m[0].length - 1) : null;
		if (params) shape = `new ${params}`;
	}
	shape = shape
		.replace(/^\|\s*/, "")
		.replace(/\(\s+/g, "(")
		.replace(/,\s*\)/g, ")");
	return shape && shape.length <= SHAPE_MAX ? code(shape) : "";
}

function exportRows(project, file) {
	const { checker, program } = project;
	const sf = program.getSourceFile(file);
	if (!sf) throw new Error(`not in program: ${file}`);
	const rows = [];
	for (const exp of checker.getExportsOfModule(
		checker.getSymbolAtLocation(sf),
	)) {
		const sym =
			exp.flags & SymbolFlags.Alias ? checker.getAliasedSymbol(exp) : exp;
		const kind = KINDS.find(([flag]) => sym.flags & flag)?.[1] ?? "value";
		let signature = "";
		if (kind === "function") signature = code(declaredSignature(program, sym));
		else if (kind === "const") {
			// Inferred types of consts like zod schemas are huge; show only short ones.
			const t = checker.getTypeOfSymbol(sym);
			const str = t ? checker.typeToString(t) : "";
			if (str.length <= 100) signature = code(str);
		} else if (kind === "interface" || kind === "type" || kind === "class")
			signature = declaredShape(program, sym, kind);
		const doc = checker.getDocumentationCommentOfSymbol(sym) ?? "";
		rows.push([
			exp.name,
			[code(exp.name), kind, signature, firstSentence(doc)],
		]);
	}
	rows.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
	return table(
		["export", "kind", "type", "summary"],
		rows.map((r) => r[1]),
	);
}

function apiLists(root) {
	const sdkPkg = JSON.parse(
		readFileSync(path.join(root, "packages/sdk/package.json"), "utf8"),
	);
	const sdkEntries = Object.entries(sdkPkg.exports).map(([sub, rel]) => [
		`@pebble3d/sdk${sub.slice(1)}`,
		path.join(root, "packages/sdk", rel),
	]);
	const rendererEntry = path.join(root, "packages/renderer/src/index.ts");
	const api = new API({ cwd: root });
	try {
		const files = [...sdkEntries.map((e) => e[1]), rendererEntry];
		const snap = api.updateSnapshot({ openFiles: files });
		const projectOf = (f) => {
			const p = snap.getDefaultProjectForFile(f);
			if (!p) throw new Error(`no TypeScript project for ${f}`);
			return p;
		};
		const sdk = sdkEntries
			.map(
				([name, f]) =>
					`### ${name}\n\nSource: \`${path.relative(root, f)}\`\n\n${exportRows(projectOf(f), f)}`,
			)
			.join("\n\n");
		const renderer = `Source: \`packages/renderer/src/index.ts\`\n\n${exportRows(projectOf(rendererEntry), rendererEntry)}`;
		return { sdk, renderer };
	} finally {
		api.close();
	}
}

/** Public methods of `class World` in the wasm-bindgen .d.ts (a regular, line-based format). */
function worldMethods(root) {
	const file = path.join(root, WORLD_DTS);
	if (!existsSync(file))
		throw new Error(`${WORLD_DTS} missing: run \`pnpm build:wasm\``);
	const lines = readFileSync(file, "utf8").split("\n");
	const start = lines.findIndex((l) => l.startsWith("export class World {"));
	if (start < 0) throw new Error(`class World not found in ${WORLD_DTS}`);
	const rows = [];
	let doc = [];
	for (let i = start + 1; i < lines.length && !lines[i].startsWith("}"); i++) {
		const l = lines[i].trim();
		if (l.startsWith("/**")) doc = [];
		if (l.startsWith("/**") || l.startsWith("*")) {
			const t = l.replace(/^\/\*\*|\*\/$|^\*/g, "").trim();
			if (t && t !== "/") doc.push(t);
			continue;
		}
		const m = l.match(/^([A-Za-z_$][\w$]*)\s*\((.*)\)\s*(?::\s*(.+?))?;$/);
		if (m) {
			const [, name, params, ret] = m;
			const sig =
				name === "constructor"
					? `new World(${params})`
					: `${name}(${params}): ${ret}`;
			const row = [code(name), code(sig), doc.join(" ")];
			if (name === "constructor") rows.unshift(row);
			else rows.push(row);
		}
		doc = [];
	}
	return `Source: \`${WORLD_DTS}\` (wasm-bindgen output; build with \`pnpm build:wasm\`). "Scratch" is the \`SCRATCH_LEN\`-float region at \`scratchPtr()\`.\n\n${table(["method", "signature", "doc"], rows)}`;
}

function apiReference(root) {
	const p = path.join(root, API_REF);
	let doc = existsSync(p) ? readFileSync(p, "utf8") : API_SKELETON;
	const { sdk, renderer } = apiLists(root);
	doc = fillRegion(doc, "api-sdk", sdk);
	doc = fillRegion(doc, "api-renderer", renderer);
	doc = fillRegion(doc, "api-world", worldMethods(root));
	return doc;
}

// ---------- llms-full.txt ----------

/** Local link targets of a markdown/text file, in order, without duplicates. */
export function localLinks(text) {
	const out = [];
	for (const m of text.matchAll(/\]\(([^)\s]+)\)/g)) {
		const t = m[1].split("#")[0];
		if (!t || /^[a-z]+:/i.test(m[1]) || out.includes(t)) continue;
		out.push(t);
	}
	return out;
}

function llmsFull(root, generated) {
	const llms = readFileSync(path.join(root, "llms.txt"), "utf8");
	let out = llms;
	for (const link of localLinks(llms)) {
		const file = path.join(root, link);
		if (!generated.has(link) && !existsSync(file))
			throw new Error(`llms.txt links a missing file: ${link}`);
		const content = generated.get(link) ?? readFileSync(file, "utf8");
		out += `\n\n===== ${link} =====\n\n${content}`;
	}
	return out;
}

// ---------- entry points ----------

/** path (relative to root) -> full content of every generated file. Pure: reads, never writes. */
export function generate(root) {
	const out = new Map();
	out.set(SCENE_REF, sceneReference(root));
	out.set(API_REF, apiReference(root));
	out.set("llms-full.txt", llmsFull(root, out));
	return out;
}

if (
	process.argv[1] &&
	path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
	const root = path.resolve(
		path.dirname(fileURLToPath(import.meta.url)),
		"../..",
	);
	const check = process.argv.includes("--check");
	const stale = [];
	for (const [rel, content] of generate(root)) {
		const p = path.join(root, rel);
		if (existsSync(p) && readFileSync(p, "utf8") === content) continue;
		stale.push(rel);
		if (!check) writeFileSync(p, content);
	}
	if (check) {
		if (stale.length) {
			console.error(
				`stale (run \`pnpm docs:gen\`):\n${stale.map((s) => `  ${s}`).join("\n")}`,
			);
			process.exit(1);
		}
		console.log("docs are current");
	} else {
		console.log(
			stale.length ? `wrote ${stale.join(", ")}` : "docs are current",
		);
	}
}
